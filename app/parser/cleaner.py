"""
文本清洗器

对原始文本进行基础规范化处理：
- 统一换行符
- 移除控制字符（保留换行、制表符）
- 压缩连续空白行
- 去除首尾空白

不做 NLP 级别的处理（分词、去停用词等），保持简单可预测。
"""

import re


def clean_text(text: str) -> str:
    """
    清洗文本，返回规范化后的字符串。

    处理步骤（按顺序）：
    1. 统一换行符（\r\n → \n）
    2. 移除控制字符（保留 \n, \t）
    3. 压缩连续空白行（3+ 空行 → 2 空行）
    4. 去除首尾空白
    """
    # 1. 统一换行符
    text = text.replace("\r\n", "\n").replace("\r", "\n")

    # 2. 移除控制字符（保留 \n 和 \t）
    #    控制字符范围: \x00-\x08, \x0b-\x0c, \x0e-\x1f
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", text)

    # 3. 压缩连续空白行：3 个及以上连续空行 → 2 个空行
    text = re.sub(r"\n{3,}", "\n\n", text)

    # 4. 去除首尾空白，但保留末尾一个换行
    text = text.strip()
    if text:
        text += "\n"

    return text
